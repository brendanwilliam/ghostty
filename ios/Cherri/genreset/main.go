// genreset writes reset_state.go for a package: one function that puts every
// package-level variable back to its initial value, so the Cherri compiler
// (a command-line program that keeps its state in globals) can be run again
// inside one long-lived process.
//
// Usage: go run ./genreset <package dir>
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	dir := os.Args[1]
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(i os.FileInfo) bool {
		n := i.Name()
		return strings.HasSuffix(n, ".go") && !strings.HasSuffix(n, "_test.go") && !strings.HasSuffix(n, "_entry.go") && n != "reset_state.go"
	}, parser.ParseComments)
	if err != nil {
		panic(err)
	}
	var body bytes.Buffer
	for _, pkg := range pkgs {
		for name, file := range pkg.Files {
			_ = name
			for _, decl := range file.Decls {
				gd, ok := decl.(*ast.GenDecl)
				if !ok || gd.Tok != token.VAR {
					continue
				}
				for _, spec := range gd.Specs {
					vs := spec.(*ast.ValueSpec)
					if embedded(gd, vs) {
						continue
					}
					emit(&body, fset, vs)
				}
			}
		}
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by genreset; DO NOT EDIT.\n\npackage main\n\nfunc resetState() {\n")
	out.Write(body.Bytes())
	out.WriteString("}\n")
	src, err := format.Source(out.Bytes())
	if err != nil {
		os.Stderr.Write(out.Bytes())
		panic(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "reset_state.go"), src, 0644); err != nil {
		panic(err)
	}
}

func embedded(gd *ast.GenDecl, vs *ast.ValueSpec) bool {
	for _, cg := range []*ast.CommentGroup{gd.Doc, vs.Doc} {
		if cg == nil {
			continue
		}
		for _, c := range cg.List {
			if strings.HasPrefix(c.Text, "//go:embed") {
				return true
			}
		}
	}
	return false
}

func text(fset *token.FileSet, n ast.Node) string {
	var b bytes.Buffer
	printer.Fprint(&b, fset, n)
	return b.String()
}

func emit(b *bytes.Buffer, fset *token.FileSet, vs *ast.ValueSpec) {
	var names []string
	for _, n := range vs.Names {
		if n.Name != "_" {
			names = append(names, n.Name)
		}
	}
	if len(names) == 0 {
		return
	}
	switch {
	case len(vs.Values) == 0:
		for _, n := range names {
			fmt.Fprintf(b, "\t%s = *new(%s)\n", n, text(fset, vs.Type))
		}
	case len(vs.Values) == len(vs.Names):
		for i, n := range vs.Names {
			if n.Name == "_" {
				continue
			}
			if vs.Type != nil {
				fmt.Fprintf(b, "\t%s = %s(%s)\n", n.Name, text(fset, vs.Type), text(fset, vs.Values[i]))
			} else {
				fmt.Fprintf(b, "\t%s = %s\n", n.Name, text(fset, vs.Values[i]))
			}
		}
	default: // var a, b = f()
		var ns []string
		for _, n := range vs.Names {
			ns = append(ns, n.Name)
		}
		fmt.Fprintf(b, "\t%s = %s\n", strings.Join(ns, ", "), text(fset, vs.Values[0]))
	}
}
